export const LOCALE_ORDER = [
  "zh-CN", "zh-TW", "en", "ja", "ko",
  "fr", "de", "es", "pt", "ru", "it", "vi"
];

const FALLBACK = "en";

export function resolveLocale(preferred) {
  if (preferred && LOCALES[preferred]) return preferred;
  if (preferred) {
    const short = String(preferred).split(/[-_]/)[0];
    const match = LOCALE_ORDER.find((code) => code === short || code.startsWith(`${short}-`));
    if (match) return match;
  }
  const nav = (typeof navigator !== "undefined" && navigator.language) || "";
  if (LOCALES[nav]) return nav;
  const navShort = nav.split(/[-_]/)[0];
  const matchNav = LOCALE_ORDER.find((code) => code === navShort || code.startsWith(`${navShort}-`));
  return matchNav || FALLBACK;
}

export function translate(locale, key, args) {
  const dict = LOCALES[locale] || LOCALES[FALLBACK];
  const template = dict[key] ?? LOCALES[FALLBACK][key] ?? key;
  if (!args || !args.length) return template;
  return template.replace(/\{(\d+)\}/g, (_, idx) => {
    const value = args[Number(idx)];
    return value === undefined || value === null ? "" : String(value);
  });
}
